"""Write the aidlc-on-archon workflow: AWS AI-DLC's 33 stages as one Archon workflow, from AI-DLC's own stage and scope tables.

Each stage after Initialization becomes a loop_group of an agent node and an approval wait (AI-DLC's gate after every
stage: approve, or ask for changes and the stage is redone). Initialization is three nodes: a bash scaffold, an agent
that looks at the workspace, and a script that turns the scope input and what detection found into one true/false per
stage, which every stage's `when:` reads. A bash node after each phase lists what the phase wrote (AI-DLC's phase check).

Writes tools/data/aidlc/files/.archon/workflows/aidlc/aidlc-on-archon/aidlc-on-archon.yaml. The workflow is for the
course's java workspace (CLAUDE.md, scripts/verify.sh, priorauth-api inside).

Usage: py -3.12 tools/make_aidlc_workflow.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from aidlc_map import (CODE, INIT_KIND, NEEDS_CODE, NEEDS_PIPELINE, PHASES, ROLE, SCOPE_ORDER, SCOPES, SLUGS, STAGES, WF_FILE,  # noqa: E402
                       WORK, key, phase_check)


def ind(text, n):
    pad = " " * n
    return "\n".join(pad + l if l else "" for l in text.splitlines())


def stage_prompt(s):
    lead = ROLE[s["lead"]]
    sup = ", ".join(ROLE[a] for a in s["support"])
    folder = s["phase"].lower()
    lines = [f"AI-DLC stage {s['n']} {s['name']} ({s['phase']}). You lead it as the team's {lead}"
             + (f"; weigh what a {sup} would say." if sup else "."),
             "The request: $USER_MESSAGE",
             "The record so far is in $ARTIFACTS_DIR/record/: read what the earlier stages wrote. Follow CLAUDE.md.",
             f"This stage's job: {WORK[s['slug']]}."]
    if s["slug"] == CODE:
        lines += ["Make the branch CLAUDE.md names, write the code and the tests, run ./scripts/verify.sh until it passes,",
                  "and commit in the code repo. Write what you did to " + f"$ARTIFACTS_DIR/record/{folder}/{s['slug']}.md."]
    else:
        lines += [f"Write $ARTIFACTS_DIR/record/{folder}/{s['slug']}.md. Change no code.",
                  "Put anything only a person can decide at the top, as numbered questions with lettered options."]
    lines += [f"Changes asked for on your previous version, if any: $LOOP_PREV.{s['slug']}-gate.output.text",
              "Return a short summary for the person who approves this stage."]
    return "\n".join(lines)


def stage_node(s, deps):
    slug = s["slug"]
    work = [f"- id: {slug}-work"]
    if slug != CODE:
        work.append("  mutates_checkout: false")
    if s["mode"] in ("subagent", "pipeline"):
        work.append("  context: fresh")
    work += ["  prompt: |", ind(stage_prompt(s), 4)]
    gate_deps = [f"{slug}-work"]
    extra = []
    if slug == CODE:
        extra = [f"- id: {slug}-verify", f"  depends_on: [{slug}-work]", "  bash: |",
                 "    log=$(mktemp)",
                 "    ./scripts/verify.sh > \"$log\" 2>&1 && echo \"verify: passed\" || echo \"verify: FAILED\"",
                 "    tail -5 \"$log\"; rm -f \"$log\""]
        gate_deps = [f"{slug}-verify"]
    gate = [f"- id: {slug}-gate", f"  depends_on: [{', '.join(gate_deps)}]", "  wait:", "    form: approval", "    attention: |",
            f"      {s['n']} {s['name']}: approve, or reject with the changes you want (the stage is redone).", "",
            f"      ${slug}-work.output"]
    if slug == CODE:
        gate += ["", f"      ${slug}-verify.output"]
    inner = "\n".join(work + extra + gate)
    return "\n".join([
        f"  - id: {slug}",
        f"    depends_on: [{', '.join(deps)}]",
        "    trigger_rule: none_failed_min_one_success",
        f"    when: \"$state-init.output.{key(slug)} == true\"",
        "    loop_group:",
        "      max_iterations: 3",
        f"      until_bash: 'decision=${slug}-gate.output.decision; [ \"$decision\" = \"approve\" ]'",
        "      nodes:",
        ind(inner, 8)])


STATE_JS = """// Generated by tools/make_aidlc_workflow.py: AI-DLC's scope lists (2.11) and two runtime rules -> one true/false per stage.
const scope = process.env.INPUTS_SCOPE || "express";
const SCOPES = __SCOPES__;
const OPTIONAL = __OPTIONAL__;
const NEEDS_CODE = __NEEDS_CODE__;
const NEEDS_PIPELINE = __NEEDS_PIPELINE__;
if (!SCOPES[scope]) { console.error(`unknown scope ${scope}: use one of ${Object.keys(SCOPES).join(", ")}`); process.exit(1); }
const greenfield = process.env.INPUTS_GREENFIELD === "true";
const pipeline = process.env.INPUTS_PIPELINE === "true";
const out = { scope };
for (const slug of OPTIONAL) {
  let on = SCOPES[scope].includes(slug);
  if (NEEDS_CODE.includes(slug) && greenfield) on = false;
  if (NEEDS_PIPELINE.includes(slug) && !pipeline) on = false;
  out[slug.replaceAll("-", "_")] = on;
}
console.log(JSON.stringify(out));"""


def build():
    optional = [s for s in SLUGS if s not in INIT_KIND]
    js = (STATE_JS.replace("__SCOPES__", json.dumps({sc: [s for s in SLUGS if s in SCOPES[sc]] for sc in SCOPE_ORDER}, separators=(",", ":")))
          .replace("__OPTIONAL__", json.dumps(optional, separators=(",", ":")))
          .replace("__NEEDS_CODE__", json.dumps(sorted(NEEDS_CODE))).replace("__NEEDS_PIPELINE__", json.dumps([s for s in SLUGS if s in NEEDS_PIPELINE], separators=(",", ":"))))
    head = f"""# Generated by tools/make_aidlc_workflow.py from AI-DLC's stage table (AI-DLC Workflows 2.11): edit the generator.
name: aidlc-on-archon
description: >-
  AWS AI-DLC's 33 stages (Initialization, Ideation, Inception, Construction, Operation) as one
  Archon workflow. Each stage is an agent node led by AI-DLC's persona for it, followed by an
  approval: approve, or reject with changes and the stage is redone. The scope input picks the
  stages, as AI-DLC's scopes do ({', '.join(SCOPE_ORDER)}). Run it from the team workspace
  root. Use when: you want AI-DLC's stages and gates without AI-DLC's engine.
  NOT for: one small change (use request-to-pr), or AI-DLC's own record format (use AI-DLC).

inputs:
  scope:
    default: express
    description: >-
      Which AI-DLC scope to run: {', '.join(f'{s} ({len(SCOPES[s])})' for s in SCOPE_ORDER)}.
      The number is the stages the scope executes in AI-DLC.

nodes:
  # ── 0 Initialization: no gates ───────────────────────────────────────
  - id: workspace-scaffold
    bash: |
      for d in ideation inception construction operation; do mkdir -p "$ARTIFACTS_DIR/record/$d"; done
      echo "record: $ARTIFACTS_DIR/record (ideation inception construction operation)"

  - id: workspace-detection
    depends_on: [workspace-scaffold]
    mutates_checkout: false
    prompt: |
      AI-DLC stage 0.2 Workspace Detection. Look at this workspace (read CLAUDE.md first): is there
      application code in it (greenfield = no code), which repos, how they are built and tested, and
      is there a CI/CD pipeline definition in any repo. Change nothing. Write
      $ARTIFACTS_DIR/record/workspace.md and return the facts.
    output_format:
      type: object
      properties:
        greenfield: {{ type: boolean }}
        has_pipeline: {{ type: boolean }}
        repos: {{ type: array, items: {{ type: string }} }}
        summary: {{ type: string }}
      required: [greenfield, has_pipeline, repos, summary]
      additionalProperties: false

  - id: state-init
    depends_on: [workspace-detection]
    runtime: bun
    with:
      scope: "$INPUTS.scope"
      greenfield: "$workspace-detection.output.greenfield"
      pipeline: "$workspace-detection.output.has_pipeline"
    script: state-init
    output_format:
      type: object
      properties:
        scope: {{ type: string }}
{ind(chr(10).join(f'{key(s)}: {{ type: boolean }}' for s in optional), 8)}
      required: [scope, {', '.join(key(s) for s in optional)}]
      additionalProperties: false
"""
    parts = [head]
    prev = "state-init"
    for i, ph in enumerate(PHASES[1:], 1):
        parts.append(f"\n  # ── {i} {ph} ─{'─' * (60 - len(ph))}\n")
        for j, s in enumerate(s for s in STAGES if s["phase"] == ph):
            parts.append(("\n" if j else "") + stage_node(s, ["state-init"] if prev == "state-init" else ["state-init", prev]) + "\n")
            prev = s["slug"]
        chk = phase_check(ph)
        parts.append("\n" + "\n".join([
            f"  - id: {chk}",
            f"    depends_on: [state-init, {prev}]",
            "    trigger_rule: none_failed_min_one_success",
            "    bash: |",
            f"      echo \"{ph}: what the phase wrote\"",
            f"      ls -1 \"$ARTIFACTS_DIR/record/{ph.lower()}\" 2>/dev/null | grep . || echo \"(none: no {ph} stage ran in this scope)\""]) + "\n")
        prev = chk
    return "".join(parts), js + "\n"


if __name__ == "__main__":
    text, js = build()
    (WF_FILE.parent / "scripts").mkdir(parents=True, exist_ok=True)
    WF_FILE.write_text(text, encoding="utf-8", newline="\n")
    (WF_FILE.parent / "scripts" / "state-init.ts").write_text(js, encoding="utf-8", newline="\n")
    print(f"wrote {WF_FILE.relative_to(WF_FILE.parents[6])}  {len(text.splitlines())} lines")
